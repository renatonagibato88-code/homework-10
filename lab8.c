#include <stdio.h>

int main() {
    int N;
    double sum = 0.0;

    // Запрашиваем у пользователя значение N
    printf("Введите целое число N: ");
    if (scanf("%d", &N) != 1 || N <= 0) {
        printf("Ошибка: N должно быть целым положительным числом.\n");
        return 1;
    }

    // Цикл для подсчета суммы ряда
    for (int i = 1; i <= N; i++) {
        sum += 1.0 / i; // Используем 1.0, чтобы деление было вещественным, а не целочисленным
    }

    // Выводим вещественный результат с высокой точностью
    printf("Вещественное значение суммы ряда: %.6lf\n", sum);

    return 0;
}
